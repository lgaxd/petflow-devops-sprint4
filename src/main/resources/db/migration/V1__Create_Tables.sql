-- Schema PostgreSQL (porte do schema Oracle original).
-- Tabelas Auxiliares (Domínio Fixo)
CREATE TABLE SPECIES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255)
);

CREATE TABLE EVENT_TYPE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    POINTS_REWARD INTEGER NOT NULL,
    CATEGORY VARCHAR(50)
);

CREATE TABLE REWARD_ACTION (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    POINTS_VALUE INTEGER NOT NULL,
    DESCRIPTION VARCHAR(255)
);

CREATE TABLE RISK_LEVEL (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    DESCRIPTION VARCHAR(255),
    MIN_SCORE INTEGER NOT NULL,
    MAX_SCORE INTEGER NOT NULL
);

-- Tabelas Principais do Sistema
CREATE TABLE TUTOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE VARCHAR(20) NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PHONE VARCHAR(20),
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CLINIC (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    ADDRESS VARCHAR(200),
    PHONE VARCHAR(20),
    CNPJ VARCHAR(18) NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PLAN (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLINIC_ID BIGINT NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(200),
    PRICE NUMERIC(10,2) NOT NULL,
    DURATION_DAYS INTEGER NOT NULL,
    POINTS_PER_EVENT INTEGER NOT NULL,
    CONSTRAINT FK_PLAN_CLINIC FOREIGN KEY (CLINIC_ID) REFERENCES CLINIC(ID)
);

CREATE TABLE PARTNER_DISCOUNT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLINIC_ID BIGINT NOT NULL,
    PARTNER_NAME VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(50),
    DISCOUNT_PERCENT NUMERIC(5,2),
    CONSTRAINT FK_PD_CLINIC FOREIGN KEY (CLINIC_ID) REFERENCES CLINIC(ID)
);

CREATE TABLE COUPON_TEMPLATE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTNER_DISCOUNT_ID BIGINT NOT NULL,
    TITLE VARCHAR(100) NOT NULL,
    DISCOUNT_VALUE NUMERIC(10,2),
    DISCOUNT_TYPE VARCHAR(50),
    POINTS_REQUIRED INTEGER NOT NULL,
    CONSTRAINT FK_CT_PD FOREIGN KEY (PARTNER_DISCOUNT_ID) REFERENCES PARTNER_DISCOUNT(ID)
);

CREATE TABLE COUPON (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEMPLATE_ID BIGINT NOT NULL,
    CODE VARCHAR(50) NOT NULL UNIQUE,
    STATUS VARCHAR(20) NOT NULL,
    EXPIRATION_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_COUPON_TEMPLATE FOREIGN KEY (TEMPLATE_ID) REFERENCES COUPON_TEMPLATE(ID)
);

CREATE TABLE PET (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TUTOR_ID BIGINT NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    BREED VARCHAR(50),
    BIRTH_DATE DATE,
    WEIGHT NUMERIC(5,2),
    SPECIES_ID BIGINT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PET_TUTOR FOREIGN KEY (TUTOR_ID) REFERENCES TUTOR(ID),
    CONSTRAINT FK_PET_SPECIES FOREIGN KEY (SPECIES_ID) REFERENCES SPECIES(ID)
);

CREATE TABLE HEALTH_EVENT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PET_ID BIGINT NOT NULL,
    CLINIC_ID BIGINT,
    EVENT_TYPE_ID BIGINT NOT NULL,
    DESCRIPTION VARCHAR(200),
    EVENT_DATE DATE NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_HE_PET FOREIGN KEY (PET_ID) REFERENCES PET(ID),
    CONSTRAINT FK_HE_CLINIC FOREIGN KEY (CLINIC_ID) REFERENCES CLINIC(ID),
    CONSTRAINT FK_HE_TYPE FOREIGN KEY (EVENT_TYPE_ID) REFERENCES EVENT_TYPE(ID)
);

CREATE TABLE SUBSCRIPTION (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PET_ID BIGINT NOT NULL,
    PLAN_ID BIGINT NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE,
    STATUS VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SUB_PET FOREIGN KEY (PET_ID) REFERENCES PET(ID),
    CONSTRAINT FK_SUB_PLAN FOREIGN KEY (PLAN_ID) REFERENCES PLAN(ID)
);

CREATE TABLE REDEEM (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TUTOR_ID BIGINT NOT NULL,
    COUPON_ID BIGINT NOT NULL,
    POINTS_USED INTEGER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_REDEEM_TUTOR FOREIGN KEY (TUTOR_ID) REFERENCES TUTOR(ID),
    CONSTRAINT FK_REDEEM_COUPON FOREIGN KEY (COUPON_ID) REFERENCES COUPON(ID)
);

CREATE TABLE REWARD_POINT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TUTOR_ID BIGINT NOT NULL,
    REWARD_ACTION_ID BIGINT NOT NULL,
    POINTS INTEGER NOT NULL,
    REFERENCE_TYPE VARCHAR(50),
    REFERENCE_ID BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_RP_TUTOR FOREIGN KEY (TUTOR_ID) REFERENCES TUTOR(ID),
    CONSTRAINT FK_RP_ACTION FOREIGN KEY (REWARD_ACTION_ID) REFERENCES REWARD_ACTION(ID)
);